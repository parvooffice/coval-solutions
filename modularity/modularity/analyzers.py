"""Per-file analysis: Python via ``ast``; other languages via masked-source heuristics.

For JS/TS, Java, Go and C/C++ we do not build a full parse tree. Instead we
blank out comments and string literals (keeping offsets and newlines intact),
match brackets once, and locate functions / types / imports with anchored
regexes. That is fast, robust to syntax we do not understand, and accurate
enough for size / complexity / coupling heuristics. Results are tagged
``parse_mode="heuristic"`` so the report can say so.
"""

from __future__ import annotations

import ast
import bisect
import contextlib
import logging
import os
import re
import signal
import threading
import warnings
from dataclasses import dataclass
from typing import Dict, Iterator, List, Optional, Tuple

from .models import FileEntry, FileMetrics, FunctionInfo, ImportRef

log = logging.getLogger(__name__)


class FileTimeout(Exception):
    """Raised when a single file takes too long to analyze."""


@dataclass(frozen=True)
class AnalysisLimits:
    max_bytes: int = 1_000_000
    file_timeout: float = 10.0


@contextlib.contextmanager
def time_limit(seconds: float) -> Iterator[None]:
    """Abort the enclosed block after *seconds* (POSIX main thread only)."""
    usable = (
        seconds
        and seconds > 0
        and hasattr(signal, "setitimer")
        and threading.current_thread() is threading.main_thread()
    )
    if not usable:
        yield
        return

    def _handler(signum, frame):  # noqa: ARG001
        raise FileTimeout()

    old = signal.signal(signal.SIGALRM, _handler)
    signal.setitimer(signal.ITIMER_REAL, seconds)
    try:
        yield
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)


