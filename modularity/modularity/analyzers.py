def _spec_matches(spec: str, vocab: Tuple[str, ...]) -> bool:
    for v in vocab:
        if spec == v or spec.startswith(v + ".") or spec.startswith(v + "/"):
            return True
    return False


def classify_infra(language: str, specs: List[str]) -> set:
    vocab = _INFRA_VOCAB.get(_FAMILY.get(language, ""), {})
    found = set()
    for spec in specs:
        spec = spec.replace("node:", "", 1) if spec.startswith("node:") else spec
        for category, names in vocab.items():
            if category not in found and _spec_matches(spec, names):
                found.add(category)
    return found


