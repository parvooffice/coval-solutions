def analyze_entry(entry: FileEntry, limits: AnalysisLimits) -> FileMetrics:
    """Analyze one file. Never raises: failures are recorded on the result."""
    fm = FileMetrics(path=entry.rel_path, language=entry.language,
                     is_test=entry.is_test, size=entry.size)
    try:
        with time_limit(limits.file_timeout):
            _analyze(entry, fm, limits)
    except FileTimeout:
        fm.skipped = "timeout"
        fm.error = f"analysis exceeded {limits.file_timeout:g}s"
    except (RecursionError, MemoryError) as exc:
        fm.parse_mode = "failed"
        fm.error = type(exc).__name__
    except Exception as exc:  # noqa: BLE001 - one bad file must not stop the run
        fm.parse_mode = "failed"
        fm.error = f"{type(exc).__name__}: {exc}"
    return fm


def _analyze(entry: FileEntry, fm: FileMetrics, limits: AnalysisLimits) -> None:
    try:
        with open(entry.abs_path, "rb") as fh:
            data = fh.read(limits.max_bytes + 1)
    except OSError as exc:
        fm.skipped = "unreadable"
        fm.error = str(exc)
        return
    if len(data) > limits.max_bytes:
        fm.skipped = "too_large"
        return
    if b"\0" in data[:8192]:
        fm.skipped = "binary"
        return
    text = data.decode("utf-8", errors="replace").lstrip("﻿")
    fm.total_lines = text.count("\n") + 1

    head = text[:1500].lower()
    if any(marker in head for marker in _GENERATED_MARKERS):
        fm.skipped = "generated"
        return
    if len(text) > 20_000 and len(text) / fm.total_lines > 300:
        fm.skipped = "minified"
        return

    if fm.language == "python":
        _analyze_python(text, fm, entry)
    else:
        _analyze_brace(text, fm, entry)
    fm.infra = classify_infra(fm.language, [r.spec for r in fm.imports])


