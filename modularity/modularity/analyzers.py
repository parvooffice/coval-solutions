_FUNC_NODES = (ast.FunctionDef, ast.AsyncFunctionDef)
_MATCH_CASE = getattr(ast, "match_case", None)
_CONTAINERS = (ast.stmt, ast.ExceptHandler) + ((_MATCH_CASE,) if _MATCH_CASE else ())
_BRANCH_NODES = (ast.If, ast.IfExp, ast.For, ast.AsyncFor, ast.While, ast.ExceptHandler)
_ABC_BASES = {"ABC", "Protocol", "ABCMeta"}


def _cyclomatic(fn: ast.AST) -> int:
    """McCabe complexity of one function body, excluding nested definitions."""
    cc = 1
    stack = list(fn.body)  # type: ignore[attr-defined]
    while stack:
        node = stack.pop()
        if isinstance(node, _FUNC_NODES + (ast.ClassDef, ast.Lambda)):
            continue
        if isinstance(node, _BRANCH_NODES):
            cc += 1
        elif isinstance(node, ast.BoolOp):
            cc += len(node.values) - 1
        elif isinstance(node, ast.comprehension):
            cc += 1 + len(node.ifs)
        elif _MATCH_CASE is not None and isinstance(node, _MATCH_CASE):
            cc += 1
        stack.extend(ast.iter_child_nodes(node))
    return cc


def _iter_defs(node: ast.AST, in_class: bool, top: bool):
    """Yield (def_node, in_class, module_or_class_level) for every def/class."""
    for child in ast.iter_child_nodes(node):
        if isinstance(child, _FUNC_NODES):
            yield child, in_class, top
            yield from _iter_defs(child, False, False)
        elif isinstance(child, ast.ClassDef):
            yield child, in_class, top
            yield from _iter_defs(child, True, True)
        elif isinstance(child, _CONTAINERS):
            yield from _iter_defs(child, in_class, top)


def _is_dunder(name: str) -> bool:
    return name.startswith("__") and name.endswith("__")


def _py_param_count(fn: ast.AST, in_class: bool) -> int:
    a = fn.args  # type: ignore[attr-defined]
    count = len(a.posonlyargs) + len(a.args) + len(a.kwonlyargs)
    count += 1 if a.vararg else 0
    count += 1 if a.kwarg else 0
    if in_class and count and (a.posonlyargs + a.args):
        first = (a.posonlyargs + a.args)[0].arg
        if first in {"self", "cls", "mcs", "mcls"}:
            count -= 1
    return count


def _is_main_guard(node: ast.AST) -> bool:
    return (
        isinstance(node, ast.If)
        and isinstance(node.test, ast.Compare)
        and isinstance(node.test.left, ast.Name)
        and node.test.left.id == "__name__"
    )


def _analyze_python(text: str, fm: FileMetrics, entry: FileEntry) -> None:
    fm.loc = sum(1 for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#"))
    base = os.path.basename(entry.rel_path)
    fm.is_boundary_file = base == "__init__.py"
    fm.is_entry_point = base == "__main__.py"
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tree = ast.parse(text, filename=entry.rel_path)
    except (SyntaxError, ValueError):
        _python_fallback(text, fm)
        return

    fm.parse_mode = "ast"
    if any(_is_main_guard(node) for node in tree.body):
        fm.is_entry_point = True

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            fm.imports.extend(ImportRef(spec=a.name) for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            fm.imports.append(
                ImportRef(spec=node.module or "", level=node.level or 0,
                          names=tuple(a.name for a in node.names))
            )

    for node, in_class, top in _iter_defs(tree, False, True):
        if isinstance(node, ast.ClassDef):
            fm.classes += 1
            methods = [c for c in node.body if isinstance(c, _FUNC_NODES)]
            fm.max_class_methods = max(fm.max_class_methods, len(methods))
            if _python_class_is_interface(node):
                fm.interface_sizes.append(len(methods))
            if top and not _is_dunder(node.name):
                _count_visibility(fm, node.name)
            continue
        end = getattr(node, "end_lineno", None) or node.lineno
        private = node.name.startswith("_") and not _is_dunder(node.name)
        fm.functions.append(
            FunctionInfo(
                name=node.name,
                lines=end - node.lineno + 1,
                complexity=_cyclomatic(node),
                params=_py_param_count(node, in_class),
                line=node.lineno,
                private=private,
            )
        )
        if top and not _is_dunder(node.name):
            _count_visibility(fm, node.name)


def _count_visibility(fm: FileMetrics, name: str) -> None:
    if name.startswith("_"):
        fm.private_members += 1
    else:
        fm.public_members += 1


def _python_class_is_interface(node: ast.ClassDef) -> bool:
    for base in node.bases:
        name = base.id if isinstance(base, ast.Name) else getattr(base, "attr", "")
        if name in _ABC_BASES:
            return True
    for kw in node.keywords:
        if kw.arg == "metaclass":
            val = kw.value
            name = val.id if isinstance(val, ast.Name) else getattr(val, "attr", "")
            if name == "ABCMeta":
                return True
    return False


_PY_DEF_RE = re.compile(r"^(\s*)(?:async\s+)?def\s+(\w+)\s*\(([^)]*)")
_PY_CLASS_RE = re.compile(r"^\s*class\s+\w+")
_PY_IMPORT_RE = re.compile(r"^\s*import\s+([\w.,\s]+)")
_PY_FROM_RE = re.compile(r"^\s*from\s+(\.*)([\w.]*)\s+import\s+(.+)")
_PY_BRANCH_RE = re.compile(r"\b(?:if|elif|for|while|except|and|or)\b")


def _python_fallback(text: str, fm: FileMetrics) -> None:
    """Regex analysis for files ``ast`` rejects (Python 2, templates, typos)."""
    fm.parse_mode = "fallback"
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if _PY_CLASS_RE.match(line):
            fm.classes += 1
        m = _PY_FROM_RE.match(line)
        if m:
            names = tuple(n.strip().split(" as ")[0] for n in m.group(3).strip("() \\").split(","))
            fm.imports.append(ImportRef(spec=m.group(2), level=len(m.group(1)), names=names))
            continue
        m = _PY_IMPORT_RE.match(line)
        if m:
            for part in m.group(1).split(","):
                part = part.strip().split(" as ")[0].strip()
                if part:
                    fm.imports.append(ImportRef(spec=part))
            continue
        m = _PY_DEF_RE.match(line)
        if m:
            indent = len(m.group(1).expandtabs())
            j = i + 1
            while j < len(lines) and (
                not lines[j].strip() or len(lines[j]) - len(lines[j].lstrip()) > indent
            ):
                j += 1
            span = lines[i:j]
            while span and not span[-1].strip():
                span.pop()
            params = [p for p in m.group(3).split(",") if p.strip() and p.strip() not in {"self", "cls"}]
            name = m.group(2)
            fm.functions.append(
                FunctionInfo(
                    name=name,
                    lines=len(span),
                    complexity=1 + sum(len(_PY_BRANCH_RE.findall(s)) for s in span[1:]),
                    params=len(params),
                    line=i + 1,
                    private=name.startswith("_") and not _is_dunder(name),
                )
            )
            if indent == 0 and not _is_dunder(name):
                _count_visibility(fm, name)
        if line.startswith("if __name__"):
            fm.is_entry_point = True


