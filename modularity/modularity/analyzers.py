# Brace languages (heuristic)
# --------------------------------------------------------------------------

_PAIR_RE = re.compile(r"[(){}]")
_CC_RE = re.compile(
    r"\b(?:if|for|while|case|catch|foreach)\b|&&|\|\||\?\?(?!=)|(?<![?])\?(?![?.>])"
)
_NON_NL = re.compile(r"[^\n]")
_CONTROL_WORDS = {
    "if", "for", "while", "switch", "catch", "return", "sizeof", "else", "do", "synchronized",
    "try", "new", "defined", "alignof", "typeof", "decltype", "static_assert", "with", "function",
    "await", "yield", "throw", "delete", "using", "namespace", "elif", "assert", "typedef",
    "super", "this", "__attribute__", "defer", "go", "select", "case", "template", "extern",
}
_MASK_CACHE: Dict[str, "re.Pattern[str]"] = {}


def _mask_regex(language: str) -> "re.Pattern[str]":
    cached = _MASK_CACHE.get(language)
    if cached is not None:
        return cached
    parts = [r"//[^\n]*", r"/\*.*?\*/"]
    if language == "java":
        parts.append(r'"""[\s\S]*?"""')
    parts.append(r'"(?:\\.|[^"\\\n])*"')
    parts.append(r"'(?:\\.|[^'\\\n])*'")
    if language in ("javascript", "typescript", "go"):
        parts.append(r"`(?:\\.|[^`\\])*`")
    pat = re.compile("|".join(parts), re.S)
    _MASK_CACHE[language] = pat
    return pat


def _blank(match: "re.Match[str]") -> str:
    s = match.group(0)
    if s.startswith("//") or s.startswith("/*"):
        return _NON_NL.sub(" ", s)
    if s.startswith('"""'):
        return '"""' + _NON_NL.sub(" ", s[3:-3]) + '"""'
    return s[0] + _NON_NL.sub(" ", s[1:-1]) + s[-1]


def mask_source(text: str, language: str) -> str:
    """Blank comments and string contents; offsets and newlines are preserved."""
    return _mask_regex(language).sub(_blank, text)


class _Src:
    """Source text plus the structural indexes the heuristics share."""

    def __init__(self, text: str, language: str) -> None:
        self.text = text
        self.masked = mask_source(text, language)
        self.line_starts = [0] + [m.end() for m in re.finditer("\n", text)]
        self.braces: Dict[int, int] = {}
        self.parens: Dict[int, int] = {}
        bstack: List[int] = []
        pstack: List[int] = []
        for m in _PAIR_RE.finditer(self.masked):
            ch = m.group()
            pos = m.start()
            if ch == "{":
                bstack.append(pos)
            elif ch == "}":
                if bstack:
                    self.braces[bstack.pop()] = pos
            elif ch == "(":
                pstack.append(pos)
            elif pstack:
                self.parens[pstack.pop()] = pos

    def line_of(self, pos: int) -> int:
        return bisect.bisect_right(self.line_starts, pos)

    def find_open_brace(self, start: int, limit: int = 300) -> Optional[int]:
        end = min(len(self.masked), start + limit)
        b = self.masked.find("{", start, end)
        s = self.masked.find(";", start, end)
        if b == -1 or (s != -1 and s < b):
            return None
        return b

    def count_params(self, open_pos: int, close_pos: int, generics: bool) -> int:
        seg = self.masked[open_pos + 1:close_pos]
        if not seg.strip() or seg.strip() == "void":
            return 0
        depth = 0
        commas = 0
        for ch in seg:
            if ch in "([{" or (generics and ch == "<"):
                depth += 1
            elif ch in ")]}" or (generics and ch == ">"):
                depth = max(0, depth - 1)
            elif ch == "," and depth == 0:
                commas += 1
        return commas + 1

    def complexity(self, open_pos: int, close_pos: int) -> int:
        return 1 + len(_CC_RE.findall(self.masked, open_pos, close_pos))

    def prev_nonspace(self, pos: int) -> str:
        i = pos - 1
        while i >= 0 and self.masked[i].isspace():
            i -= 1
        return self.masked[i] if i >= 0 else ""

    def statement_prefix(self, pos: int) -> str:
        """Text between the previous ``; { }`` and *pos* (modifiers, return type)."""
        start = max(0, pos - 160)
        chunk = self.masked[start:pos]
        cut = max(chunk.rfind(";"), chunk.rfind("{"), chunk.rfind("}"))
        return chunk[cut + 1:]


def _analyze_brace(text: str, fm: FileMetrics, entry: FileEntry) -> None:
    lang = fm.language
    src = _Src(text, lang)
    fm.parse_mode = "heuristic"
    fm.loc = sum(1 for ln in src.masked.split("\n") if ln.strip())
    base = os.path.basename(entry.rel_path)
    stem = os.path.splitext(base)[0]

    if lang == "c" and base.endswith(".h") and re.search(
        r"\bclass\s+\w+\s*[:{]|\bnamespace\b|\btemplate\s*<", src.masked
    ):
        fm.language = lang = "cpp"

    if lang in ("javascript", "typescript"):
        _analyze_js(src, fm, stem, base)
    elif lang == "java":
        _analyze_java(src, fm, base)
    elif lang == "go":
        _analyze_go(src, fm, base)
    else:
        _analyze_c(src, fm, base)


def _count_member_lines(src: _Src, open_pos: int) -> int:
    close = src.braces.get(open_pos)
    if close is None:
        return 0
    body = src.masked[open_pos + 1:close]
    return sum(1 for ln in body.split("\n") if ln.strip() and ln.strip() not in "{}")


# -- JavaScript / TypeScript ------------------------------------------------

_JS_FUNC_RE = re.compile(
    r"(?<![\w$.])function\b\s*\*?\s*([A-Za-z_$][\w$]*)?\s*(?:<[^()]*?>)?\s*(?=\()"
)
_JS_ARROW_RE = re.compile(
    r"(?:\b(?:const|let|var)\s+)?([A-Za-z_$][\w$]*)\s*(?::[^=;(){}]+?)?[:=]\s*(?:async\s*)?"
    r"(?:\([^()]*(?:\([^()]*\)[^()]*)*\)|[A-Za-z_$][\w$]*)\s*(?::\s*[^=;{}]+?)?\s*=>"
)
_JS_METHOD_RE = re.compile(
    r"^[ \t]*(?:(?:public|private|protected|static|async|readonly|override|abstract|get|set)\s+)*"
    r"\*?\s*(#?[A-Za-z_$][\w$]*)\s*(?:<[^()]*?>)?\s*(?=\()",
    re.M,
)
_JS_TYPE_RE = re.compile(r"(?<![\w$.])(class|interface)\s+([A-Za-z_$][\w$]*)")
_JS_IMPORT_RE = re.compile(
    r"(?:\bfrom\s*|\bimport\s*\(?\s*|\brequire\s*\(\s*)([\"'])( *)\1"
)
_JS_EXPORT_RE = re.compile(
    r"^[ \t]*export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|let|var|interface|type|enum)\b"
    r"|^[ \t]*export\s*\{|^[ \t]*export\s+default\b|\bmodule\.exports\b|\bexports\.\w+\s*=",
    re.M,
)
_JS_PRIVATE_RE = re.compile(r"(?<![\w$])private\s|(?<![\w$#])#[A-Za-z_]\w*\s*[(=;:]")


def _analyze_js(src: _Src, fm: FileMetrics, stem: str, base: str) -> None:
    masked = src.masked
    seen_bodies: set = set()
    generics = fm.language == "typescript"

    def add(name: str, start: int, popen: Optional[int], body_open: Optional[int]) -> None:
        if body_open is None or body_open in seen_bodies:
            return
        close = src.braces.get(body_open)
        if close is None:
            return
        seen_bodies.add(body_open)
        pclose = src.parens.get(popen) if popen is not None else None
        fm.functions.append(
            FunctionInfo(
                name=name or "<anonymous>",
                lines=src.line_of(close) - src.line_of(start) + 1,
                complexity=src.complexity(body_open, close),
                params=src.count_params(popen, pclose, generics) if popen is not None and pclose else 0,
                line=src.line_of(start),
                private=name.startswith(("_", "#")),
            )
        )

    for m in _JS_FUNC_RE.finditer(masked):
        popen = m.end()
        pclose = src.parens.get(popen)
        if pclose is not None:
            add(m.group(1) or "", m.start(), popen, src.find_open_brace(pclose + 1, 200))

    for m in _JS_ARROW_RE.finditer(masked):
        nxt = m.end()
        while nxt < len(masked) and masked[nxt] in " \t\r\n":
            nxt += 1
        popen = masked.find("(", m.start(), m.end())
        if nxt < len(masked) and masked[nxt] == "{":
            add(m.group(1), m.start(), popen if popen != -1 else None, nxt)
        else:  # expression-bodied arrow: count its line
            end = min(
                (p for p in (masked.find("\n", nxt), masked.find(";", nxt)) if p != -1),
                default=len(masked),
            )
            fm.functions.append(
                FunctionInfo(
                    name=m.group(1), lines=1,
                    complexity=1 + len(_CC_RE.findall(masked, nxt, end)),
                    params=0, line=src.line_of(m.start()),
                    private=m.group(1).startswith(("_", "#")),
                )
            )

    for m in _JS_METHOD_RE.finditer(masked):
        name = m.group(1)
        if name in _CONTROL_WORDS:
            continue
        popen = m.end()
        pclose = src.parens.get(popen)
        if pclose is None:
            continue
        brace = src.find_open_brace(pclose + 1, 200)
        if brace is None:
            continue
        between = masked[pclose + 1:brace]
        if "=" in between or "(" in between:
            continue
        add(name, m.start(1), popen, brace)

    for m in _JS_TYPE_RE.finditer(masked):
        open_pos = src.find_open_brace(m.end(), 300)
        if open_pos is None:
            continue
        if m.group(1) == "class":
            fm.classes += 1
        else:
            fm.interface_sizes.append(_count_member_lines(src, open_pos))

    for m in _JS_IMPORT_RE.finditer(masked):
        spec = src.text[m.start(2):m.end(2)].strip()
        if spec:
            fm.imports.append(ImportRef(spec=spec))

    exports = len(_JS_EXPORT_RE.findall(masked))
    private_marked = len(_JS_PRIVATE_RE.findall(masked)) + sum(1 for f in fm.functions if f.private)
    fm.public_members = exports
    fm.private_members = private_marked
    if exports:
        fm.private_members += max(0, len(fm.functions) - exports - private_marked)

    fm.is_boundary_file = stem == "index"
    shebang = src.text.startswith("#!")
    fm.is_entry_point = (
        shebang
        or "require.main === module" in masked
        or stem in {"main", "server", "cli", "app", "bootstrap", "start"}
    )


# -- Java / C / C++ (shared "definition followed by { body }" strategy) -------

_NAME_BEFORE_RE = re.compile(r"([A-Za-z_~$][\w$~]*(?:::[A-Za-z_~$][\w$~]*)*)\s*$")
_DEF_PREV_OK = set("]>)*&;{}:")
_BETWEEN_OK_RE = re.compile(r"[\s\w.,<>?\[\]:*&]*\Z")


def _scan_definitions(src: _Src, generics: bool) -> List[Tuple[str, int, int, int, str]]:
    """Find ``name(params) [qualifiers] {`` definitions.

    Returns (name, name_start, paren_open, body_open, prefix) tuples.
    """
    out = []
    seen_bodies: set = set()
    masked = src.masked
    for popen in sorted(src.parens):
        pclose = src.parens[popen]
        body = src.find_open_brace(pclose + 1, 250)
        if body is None or body in seen_bodies:
            continue
        if not _BETWEEN_OK_RE.match(masked, pclose + 1, body):
            continue
        m = _NAME_BEFORE_RE.search(masked, max(0, popen - 120), popen)
        if not m:
            continue
        name = m.group(1)
        short = name.split("::")[-1]
        if short in _CONTROL_WORDS:
            continue
        prev = src.prev_nonspace(m.start(1))
        if prev and not (prev.isalnum() or prev == "_" or prev in _DEF_PREV_OK):
            continue
        seen_bodies.add(body)
        out.append((name, m.start(1), popen, body, src.statement_prefix(m.start(1))))
    return out


_JAVA_IMPORT_RE = re.compile(r"^[ \t]*import\s+(?:static\s+)?([\w.]+(?:\.\*)?)\s*;", re.M)
_JAVA_PACKAGE_RE = re.compile(r"^[ \t]*package\s+([\w.]+)\s*;", re.M)
_JAVA_TYPE_RE = re.compile(r"(?<![\w$.@])(class|interface|enum|record)\s+([A-Za-z_$][\w$]*)")


def _add_defs(src: _Src, fm: FileMetrics, defs, generics: bool) -> None:
    for name, start, popen, body, _prefix in defs:
        close = src.braces.get(body)
        pclose = src.parens.get(popen)
        if close is None or pclose is None:
            continue
        short = name.split("::")[-1]
        fm.functions.append(
            FunctionInfo(
                name=short,
                lines=src.line_of(close) - src.line_of(start) + 1,
                complexity=src.complexity(body, close),
                params=src.count_params(popen, pclose, generics),
                line=src.line_of(start),
            )
        )


def _analyze_java(src: _Src, fm: FileMetrics, base: str) -> None:
    masked = src.masked
    defs = _scan_definitions(src, True)
    _add_defs(src, fm, defs, True)
    for fn, d in zip(fm.functions, defs):
        fn.private = "private" in d[4].split()

    for m in _JAVA_IMPORT_RE.finditer(masked):
        fm.imports.append(ImportRef(spec=m.group(1)))
    pm = _JAVA_PACKAGE_RE.search(masked)
    if pm:
        fm.package = pm.group(1)

    for m in _JAVA_TYPE_RE.finditer(masked):
        open_pos = src.find_open_brace(m.end(), 400)
        if open_pos is None:
            continue
        if m.group(1) == "interface":
            fm.interface_sizes.append(_count_member_lines(src, open_pos))
        else:
            fm.classes += 1

    fm.public_members = len(re.findall(r"\bpublic\b", masked))
    fm.private_members = len(re.findall(r"\bprivate\b", masked))
    fm.is_boundary_file = base == "package-info.java"
    fm.is_entry_point = bool(re.search(r"\bstatic\s+void\s+main\s*\(", masked))


# -- Go ----------------------------------------------------------------------

_GO_FUNC_RE = re.compile(
    r"\bfunc\s*(?:\(([^()]*)\)\s*)?([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*(?=\()"
)
_GO_TYPE_RE = re.compile(r"\btype\s+([A-Za-z_]\w*)\s+(struct|interface)\s*\{")
_GO_IMPORT_BLOCK_RE = re.compile(r"^[ \t]*import\s*\(", re.M)
_GO_IMPORT_ONE_RE = re.compile(r"^[ \t]*import\s+(?:[\w.]+\s+)?(\")( *)\"", re.M)
_GO_IMPORT_LINE_RE = re.compile(r"(?:[\w.]+\s+)?(\")( *)\"")
_GO_PACKAGE_RE = re.compile(r"^[ \t]*package\s+(\w+)", re.M)


def _analyze_go(src: _Src, fm: FileMetrics, base: str) -> None:
    masked = src.masked
    for m in _GO_FUNC_RE.finditer(masked):
        popen = m.end()
        pclose = src.parens.get(popen)
        if pclose is None:
            continue
        body = src.find_open_brace(pclose + 1, 300)
        close = src.braces.get(body) if body is not None else None
        if body is None or close is None:
            continue
        name = m.group(2)
        exported = name[:1].isupper()
        fm.functions.append(
            FunctionInfo(
                name=name,
                lines=src.line_of(close) - src.line_of(m.start()) + 1,
                complexity=src.complexity(body, close) + len(re.findall(r"\bselect\b", masked[body:close])),
                params=src.count_params(popen, pclose, False),
                line=src.line_of(m.start()),
                private=not exported,
            )
        )
        if exported:
            fm.public_members += 1
        else:
            fm.private_members += 1

    for m in _GO_TYPE_RE.finditer(masked):
        open_pos = m.end() - 1
        if m.group(2) == "interface":
            fm.interface_sizes.append(_count_member_lines(src, open_pos))
        else:
            fm.classes += 1
        if m.group(1)[:1].isupper():
            fm.public_members += 1
        else:
            fm.private_members += 1

    for m in _GO_IMPORT_BLOCK_RE.finditer(masked):
        popen = m.end() - 1
        pclose = src.parens.get(popen)
        if pclose is None:
            continue
        for im in _GO_IMPORT_LINE_RE.finditer(masked, popen, pclose):
            spec = src.text[im.start(2):im.end(2)].strip()
            if spec:
                fm.imports.append(ImportRef(spec=spec))
    for m in _GO_IMPORT_ONE_RE.finditer(masked):
        spec = src.text[m.start(2):m.end(2)].strip()
        if spec:
            fm.imports.append(ImportRef(spec=spec))

    pm = _GO_PACKAGE_RE.search(masked)
    if pm:
        fm.package = pm.group(1)
    fm.is_boundary_file = base == "doc.go"
    fm.is_entry_point = fm.package == "main" and any(f.name == "main" for f in fm.functions)


# -- C / C++ -----------------------------------------------------------------

_C_INCLUDE_RE = re.compile(r"^[ \t]*#[ \t]*include\b", re.M)
_C_INCLUDE_SPEC_RE = re.compile(r"#\s*include\s*([<\"])([^>\"\n]+)[>\"]")
_C_TYPE_RE = re.compile(r"(?<![\w$])(class|struct)\s+(?:[A-Z_]+\s+)?([A-Za-z_]\w*)\s*(?::[^;{()]*)?\{")
_C_PURE_RE = re.compile(r"=\s*0\s*;")
_C_MAIN_RE = re.compile(r"\bint\s+main\s*\(")
_C_STD_HEADERS = {
    "stdio.h", "stdlib.h", "string.h", "math.h", "stdint.h", "stddef.h", "stdbool.h", "errno.h",
    "assert.h", "ctype.h", "limits.h", "time.h", "signal.h", "unistd.h", "fcntl.h", "pthread.h",
}


def _analyze_c(src: _Src, fm: FileMetrics, base: str) -> None:
    masked = src.masked
    defs = _scan_definitions(src, True)
    _add_defs(src, fm, defs, True)
    for fn, d in zip(fm.functions, defs):
        prefix = d[4].split()
        fn.private = "static" in prefix
        if fn.private:
            fm.private_members += 1
        else:
            fm.public_members += 1

    for m in _C_INCLUDE_RE.finditer(masked):
        line_end = src.text.find("\n", m.start())
        line = src.text[m.start(): line_end if line_end != -1 else len(src.text)]
        inc = _C_INCLUDE_SPEC_RE.search(line)
        if inc:
            spec = inc.group(2).strip()
            kind = "local" if inc.group(1) == '"' else "system"
            fm.imports.append(ImportRef(spec=spec, level=0 if kind == "local" else 1))

    for m in _C_TYPE_RE.finditer(masked):
        open_pos = m.end() - 1
        close = src.braces.get(open_pos)
        fm.classes += 1
        if close is not None:
            pure = len(_C_PURE_RE.findall(masked, open_pos, close))
            if pure:
                fm.interface_sizes.append(pure)

    fm.private_members += len(re.findall(r"\bprivate\s*:", masked)) + len(
        re.findall(r"\bnamespace\s*\{", masked)
    )
    fm.public_members += len(re.findall(r"\bpublic\s*:", masked))
    fm.is_entry_point = bool(_C_MAIN_RE.search(masked))
